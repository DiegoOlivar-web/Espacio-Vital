CREATE TABLE IF NOT EXISTS categorias (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL UNIQUE,
    descripcion TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS servicios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT NOT NULL DEFAULT '',
    imagen_url TEXT NOT NULL DEFAULT '',
    categoria_id INTEGER NOT NULL REFERENCES categorias(id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_servicios_categoria ON servicios(categoria_id);

CREATE TABLE IF NOT EXISTS hero_slides (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden INTEGER NOT NULL DEFAULT 0,
    imagen_url TEXT NOT NULL DEFAULT '',
    eyebrow VARCHAR(150) NOT NULL DEFAULT '',
    titulo VARCHAR(300) NOT NULL DEFAULT '',
    parrafo TEXT NOT NULL DEFAULT '',
    boton_texto VARCHAR(150) NOT NULL DEFAULT '',
    boton_href TEXT NOT NULL DEFAULT '',
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX IF NOT EXISTS idx_hero_slides_orden ON hero_slides(orden);